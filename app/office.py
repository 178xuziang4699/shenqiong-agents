# 有明确「源文件 → 目标文件」路径的，交给原有工作流，不由办公引擎接管
_PATH_IN_OUT = re.compile(r"(samples|output|out|data|docs)/[\w\u4e00-\u9fff./-]+\.\w+")


def is_office(text: str) -> bool:
    """是否属于「要产出一份文档」的办公需求。"""
    q = (text or "").strip()
    if not q or len(q) > 2000:
        return False
    # 明确的文件搬运 / 素材整理任务：保留原有工作流能力
    if _PATH_IN_OUT.search(q) and any(k in q for k in ("整理成", "读取", "入库", "转换", "导出为")):
        return False
    if any(k in q for k in _RESEARCH):
        return True
    if not any(k in q for k in _WRITE_VERBS):
        return False
    # 有写作动词 + 任一文种关键词
    return any(any(k in q.lower() for k in spec[1]) for spec in DOC_SPECS.values())


def detect(text: str) -> tuple[str, str]:
    """返回 (文种 key, 主题)。识别不到文种时按通用报告处理。"""
    q = (text or "").strip()
    if any(k in q for k in _RESEARCH):
        key = "research"
    else:
        key = ""
        # 长关键词优先，避免「报告」抢走「调研报告」
        for k, spec in sorted(DOC_SPECS.items(), key=lambda kv: -max(len(x) for x in kv[1][1])):
            if any(w in q.lower() for w in spec[1]):
                key = k
                break
        if not key:
            key = "report"
    return key, topic_of(q, key)


def topic_of(text: str, key: str) -> str:
    """从原话里抽出主题，让文档标题与正文真的贴合用户需求。"""
    q = text.strip()
    # 「提示词优化」产出的标准提示词（或用户手写的长指令）带角色/任务/格式/约束等结构，
    # 不能把整段当标题：优先从「关于 X 的 / 围绕 X」中抽出核心主题。
    _LONG_HINT = ("角色与背景", "具体任务", "输出格式", "约束", "你是一名", "你是一位",
                  "请撰写", "请以", "篇幅", "字数", "输出要求")
    if len(q) >= 45 or any(h in q for h in _LONG_HINT):
        m = re.search(
            r"(?:关于|围绕|针对)[「『\"']?([^「」『』\"'，,。；;：:]{2,26}?)"
            r"(?:的|，|,|。|；|：|:|$)", q)
        if m:
            cand = re.sub(r"^(一份|一篇|一个|关于|针对|围绕|请|帮我|写|撰写)+", "",
                          m.group(1)).strip()
            for spec in DOC_SPECS.values():
                for w in sorted(spec[1], key=len, reverse=True):
                    if len(w) >= 2:
                        cand = cand.replace(w, "")
            cand = cand.strip(" 的、，,。:：-—_")
            if len(cand) >= 2:
                return cand[:24]
    # 口语需求常带「，写一份…」之类的补充说明，标题只取第一层意思
    q = re.split(r"[，,。；;！!？?\n]", q)[0].strip()
    # 去掉礼貌前缀与写作动词
    q = re.sub(r"^(帮我|请|麻烦|给我|帮忙|能不能|可以|需要你|我要|我想|来|帮我做)+", "", q)
    q = re.sub(r"^(发一封|来一封|写一封|拟一封|写一份|做一份|出一份|来一份|生成一份|整理一份)+", "", q)
    q = re.sub(r"^(写|起草|拟|生成|做|出|整理|编制|撰写|准备|输出|来|搞|弄)+", "", q)
    q = re.sub(r"^(一份|一个|篇|个|份|关于)+", "", q)
    q = re.sub(r"^调研(一下|份|个)?|^研究一下|^分析一下", "", q)
    q = re.sub(r"(调研|研究)报告$|(的)?(调研|研究|分析)?报告$|报告$", "", q)
    q = re.sub(r"^(关于|针对|围绕)", "", q)
    # 去掉文种尾巴与常见修饰
    for spec in DOC_SPECS.values():
        for w in sorted(spec[1], key=len, reverse=True):
            if len(w) >= 2:
                q = q.replace(w, "")
    q = re.sub(r"(一下|一份|一篇|详细|完整|正式|一份完整的|结构化|的|地|得|吧|啊|呗|嘛|哦|哈|写|，|,)+$", "", q)
    q = q.replace("的工作", "工作")
    q = re.sub(r"[\s，。！？、,!?;；:：]+$", "", q.strip())
    q = q.strip(" 的、，,。:：-—_")
    if not q or len(q) < 2:
        return {"research": "目标市场", "weekly": "本周工作", "daily": "今日工作",
                "summary": "本阶段工作", "minutes": "项目例会"}.get(key, "工作事项")
    return q[:40]


def safe_filename(topic: str, key: str) -> str:
    slug = re.sub(r"[^\w\u4e00-\u9fff]+", "_", topic).strip("_")[:24] or "文档"
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return f"output/{DOC_SPECS.get(key, ('文档',(),''))[0]}_{slug}_{stamp}.md"


