def render(key: str, topic: str, source_zh: str = "本地结构化模板") -> str:
    """把章节定义渲染成一份完整 Markdown 文档。"""
    zh = DOC_SPECS.get(key, ("文档", (), "{topic}"))[0]
    title_tpl = DOC_SPECS.get(key, ("文档", (), "{topic}"))[2]
    title = title_tpl.replace("{topic}", topic)
    date_str = datetime.now().strftime("%Y 年 %m 月 %d 日")
    lines = [f"# {title}", "",
             f"> 文档类型：{zh}　|　主题：{topic}　|　生成时间：{date_str}　|　生成方式：{source_zh}", ""]
    for sec in _sections(key, topic):
        # 表格章节写成 4 元组（标题, table, 表头, 数据行）更易读，这里统一归一
        if len(sec) == 4:
            sec_title, kind, head, rows = sec
            payload = (head, rows)
        else:
            sec_title, kind, payload = sec
        lines += [f"## {sec_title}", ""]
        if kind == "p":
            text = str(payload).replace("{topic}", topic).replace("{date}", date_str)
            lines += [text, ""]
        elif kind in ("ul", "ol"):
            for i, item in enumerate(payload, 1):
                text = str(item).replace("{topic}", topic).replace("{date}", date_str)
                lines.append(f"- {text}" if kind == "ul" else f"{i}. {text}")
            lines.append("")
        elif kind == "table":
            head, rows = payload
            lines.append("| " + " | ".join(str(h) for h in head) + " |")
            lines.append("| " + " | ".join("---" for _ in head) + " |")
            for row in rows:
                cells = [str(c).replace("{topic}", topic).replace("{date}", date_str) for c in row]
                lines.append("| " + " | ".join(cells) + " |")
            lines.append("")
    lines += ["---", "",
              "> 说明：本文档由平台办公引擎生成。涉及具体数字与外部事实的内容请以权威来源核实后引用；",
              "> 接入模型 API 时，全文由模型按需求撰写，上表与章节结构作为质量基线。", ""]
    return "\n".join(lines)


def summary_line(key: str, topic: str, content: str) -> str:
    """给用户看的自然语言汇报——先说做了什么、结论是什么，不甩内部字段。"""
    zh = DOC_SPECS.get(key, ("文档", (), ""))[0]
    chars = len(content)
    lines = content.splitlines()
    heads = [l[3:].strip() for l in lines if l.startswith("## ")]
    toc = "、".join(heads[:5]) + ("等" if len(heads) > 5 else "")
    # 从文档自身的摘要 / 概述章节里抽一句，作为「结论先说」，避免通用套话
    excerpt = ""
    for i, line in enumerate(lines):
        if line.startswith("## ") and any(k in line for k in ("摘要", "概述", "背景", "结论")):
            for nxt in lines[i + 1:i + 6]:
                s = nxt.strip()
                if s and not s.startswith(("#", "|", "-", ">", "*")) and not s[:2].rstrip(".").isdigit():
                    excerpt = re.sub(r"[*`]+", "", s)
                    break
            if excerpt:
                break
    if len(excerpt) > 150:
        excerpt = excerpt[:150] + "…"
    core = f"核心结论：{excerpt}" if excerpt else (
        f"文档围绕「{topic}」展开，含 {len(heads)} 个章节、表格与可执行建议。")
    return (f"已经把「{topic}」写成一份**{zh}**，共 {chars} 字、{len(heads)} 个章节"
            f"（{toc}）。已保存为文件，下面可直接查看全文或下载。\n\n{core}\n\n"
            "文中涉及具体数字、机构名单的地方都标了「待核实」，我没有替你编数据。")


class OfficeEngine:
    """办公产出入口。构造时注入 LLM（可为 None）；落盘由 Supervisor 负责。"""

    def __init__(self, llm=None):
        self.llm = llm

    def produce(self, text: str) -> dict:
        key, topic = detect(text)
        source_zh = "本地结构化模板（离线兜底）"
        content = ""
        if self.llm is not None and getattr(self.llm, "enabled", False):
            try:
                content = self.llm.write_document(text, DOC_SPECS[key][0], topic)
                if content and len(content.strip()) >= 200:
                    content = self._ensure_document(content, key, topic, "模型生成")
                    source_zh = "已接入模型按需求撰写"
            except Exception:
                content = ""  # 模型不可用 → 静默降级到模板，由 Supervisor 记录告警
        if not content:
            content = render(key, topic)
        path = safe_filename(topic, key)
        return {
            "ok": True, "doc_type": key, "doc_type_zh": DOC_SPECS[key][0],
            "topic": topic, "title": DOC_SPECS[key][2].replace("{topic}", topic),
            "path": path, "content": content, "chars": len(content),
            "lines": len(content.splitlines()), "source_zh": source_zh,
            "summary": summary_line(key, topic, content),
        }

    @staticmethod
    def _ensure_document(raw: str, key: str, topic: str, source: str) -> str:
        """模型可能漏标题或带代码块围栏，统一补全成规范文档。"""
        t = (raw or "").strip()
        if t.startswith("```"):
            body = t.splitlines()[1:]
            if body and body[-1].strip().startswith("```"):
                body = body[:-1]
            t = "\n".join(body).strip()
        if not t.startswith("#"):
            t = f"# {DOC_SPECS[key][2].replace('{topic}', topic)}\n\n" + t
        date_str = datetime.now().strftime("%Y 年 %m 月 %d 日")
        if "生成方式" not in t:
            t += ("\n\n---\n\n> 生成时间：" + date_str + "　|　生成方式：" + source
                  + "　|　涉及具体数字请核实权威来源后引用。\n")
        return t + "\n"

    @staticmethod
    def catalogue() -> list[dict]:
        return [{"key": k, "name": v[0], "title": v[2],
                 "sample": v[2].replace("{topic}", "德国人工智能市场")}
                for k, v in DOC_SPECS.items()]
